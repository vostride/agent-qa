describe('INIT-GUIDE-LIFECYCLE: init generates the thin knowledge guide', () => {
  it('fresh init writes the generated guide into the knowledge root', async () => {
    const dir = tempProject()
    await runInit(dir)

    expect(existsSync(join(dir, GUIDE))).toBe(true)
    expect(readFileSync(join(dir, GUIDE), 'utf8')).toBe(buildKnowledgeAgentGuide())
    const created = stdout().match(/ {2}Created:\n([\s\S]*?)(?:\n {2}(?:Updated|Preserved|Next steps):|$)/)?.[1] ?? ''
    expect(created).toContain(GUIDE)
  })

  it('keeps the guide thin, generated and truthful about the layout', () => {
    const guide = buildKnowledgeAgentGuide()
    const lines = guide.split('\n')
    expect(guide.endsWith('\n')).toBe(true)
    expect(lines.length).toBeGreaterThanOrEqual(30)
    expect(lines.length).toBeLessThanOrEqual(50)
    expect(lines[0]).toMatch(/^# agent-qa knowledge/)
    expect(guide).toContain('Generated by agent-qa init')
    for (const needle of [
      'memory/<product>/bundles/<id>/', 'policies/', 'memory/index/', 'memory/queue/', '.lease', '.epoch', 'SQLite',
      'record.md', 'agent-qa skills', KNOWLEDGE_SKILL_NAME,
    ]) {
      expect(guide, needle).toContain(needle)
    }
    for (const row of AGENT_QUESTION_MAP) {
      expect(guide, row.cli).toContain(row.cli)
      expect(guide, row.mcp).toContain(row.mcp)
    }
    expect(guide).toMatch(/never edit files under agent-qa-knowledge\/ yourself/i)
    // The change line names the direct tool.
    expect(lines.filter((line) => line.includes('agent_qa_change_knowledge'))).toHaveLength(1)
  })

  it('answers questions overview first, naming only verbs and tools that exist', () => {
    expect(AGENT_QUESTION_MAP[0]).toMatchObject({ mcp: 'agent_qa_get_run_overview' })
    expect(AGENT_QUESTION_MAP[0]!.cli.startsWith('agent-qa runs overview ')).toBe(true)
    expect(AGENT_QUESTION_MAP.map((row) => row.mcp).sort()).toEqual([
      'agent_qa_diff_knowledge_records',
      'agent_qa_explain_brief',
      'agent_qa_get_run_evidence',
      'agent_qa_get_run_knowledge',
      'agent_qa_get_run_overview',
      'agent_qa_inspect_knowledge_records',
      'agent_qa_list_knowledge_bundles',
      'agent_qa_list_knowledge_gates',
      'agent_qa_list_runs',
      'agent_qa_show_knowledge_record',
    ])
    const tools = new Set(AGENT_QA_TOOL_PROJECTIONS.map((projection) => projection.name))
    for (const row of AGENT_QUESTION_MAP) {
      expect(tools.has(row.mcp), row.mcp).toBe(true)
      expect(row.cli.startsWith('agent-qa '), row.cli).toBe(true)
      expect(liveCommandPath(row.cli).split(' '), row.cli).toHaveLength(2)
    }
    const guide = buildKnowledgeAgentGuide()
    for (const tool of guide.match(/agent_qa_[a-z_]+/g) ?? []) expect(tools.has(tool), tool).toBe(true)
    const commands = guide.match(/`npx agent-qa [a-z][a-z -]*/g) ?? []
    expect(commands.length).toBeGreaterThanOrEqual(AGENT_QUESTION_MAP.length)
    for (const command of commands) {
      expect(liveCommandPath(command.slice('`npx '.length)).length, command).toBeGreaterThan(0)
    }
  })

  it('regenerates the guide under --force while user-owned knowledge files are preserved', async () => {
    const dir = tempProject()
    await runInit(dir)
    writeFileSync(join(dir, GUIDE), 'hand edited\n')
    writeFileSync(join(dir, 'agent-qa-knowledge', 'README.md'), 'my readme\n')
    const outcomes: string[] = []

    await runInit(dir, ['--force'], {
      onComplete: (results) => {
        for (const result of results) outcomes.push(`${result.outcome} ${result.path}`)
      },
    })

    expect(readFileSync(join(dir, GUIDE), 'utf8')).toBe(buildKnowledgeAgentGuide())
    expect(outcomes).toContain(`updated ${join(dir, GUIDE)}`)
    expect(readFileSync(join(dir, 'agent-qa-knowledge', 'README.md'), 'utf8')).toBe('my readme\n')
  })

  it('keeps the already-initialized refusal unchanged and writes no guide', async () => {
    const dir = tempProject()
    await runInit(dir)
    unlinkSync(join(dir, GUIDE))
    log.mockClear()

    await runInit(dir)

    expect(stdout()).toContain(`Project is already initialized at ${dir}. Use --force to rebuild it.`)
    expect(existsSync(join(dir, GUIDE))).toBe(false)
    expect(stdout()).not.toContain(pointerBlock())
    expect(existsSync(join(dir, 'AGENTS.md'))).toBe(false)
  })

  it('passes the instruction-branding validator, which reds a known-bad generated document', async () => {
    const validator = await import(
      /* @vite-ignore */ pathToFileURL(join(repoRoot, 'scripts', 'validate-agent-instructions.mjs')).href
    ) as { validateGeneratedInstructions(documents: readonly { label: string; body: string }[]): string[] }
    const documents = [
      { label: GUIDE, body: buildKnowledgeAgentGuide() },
      { label: 'root AGENTS.md pointer', body: pointerBlock() },
    ]
    expect(validator.validateGeneratedInstructions(documents)).toEqual([])
    expect(validator.validateGeneratedInstructions([{ label: GUIDE, body: `${documents[0]!.body}AgentQA\n` }]))
      .toEqual([`${GUIDE} contains forbidden branding: AgentQA`])
  })
})

