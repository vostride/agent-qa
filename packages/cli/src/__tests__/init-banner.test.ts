import { readFileSync } from 'node:fs'

import { describe, expect, it } from 'vitest'

import { BANNER_GAP, BANNER_ROWS, BANNER_WIDTH } from '../init-ui/banner-art.js'
import { renderBanner } from '../init-ui/banner.js'
import { brandPalette, colorLevelFor } from '../init-ui/palette.js'

const ESCAPE = '\x1b['
const tty = { isTTY: true }
const pipe = { isTTY: false }

describe('the committed banner art', () => {
  it('is half blocks only, five or six lines, within its declared width of at most 69', () => {
    expect(BANNER_ROWS.length).toBeGreaterThanOrEqual(5)
    expect(BANNER_ROWS.length).toBeLessThanOrEqual(6)
    expect(BANNER_WIDTH).toBeLessThanOrEqual(69)
    for (const [chevron, wordmark] of BANNER_ROWS) {
      expect(chevron + wordmark).toMatch(/^[▀▄█ ]*$/)
      expect(chevron.length + BANNER_GAP + wordmark.length).toBeLessThanOrEqual(BANNER_WIDTH)
    }
  })

  it('names the script that writes it in its header', () => {
    const source = readFileSync(new URL('../init-ui/banner-art.ts', import.meta.url), 'utf8')
    expect(source.split('\n')[0]).toBe(
      '// Generated by scripts/render-banner.mjs (pnpm --filter agent-qa render:banner). Do not edit.',
    )
  })
})

describe('renderBanner', () => {
  const palette = brandPalette({ background: 'dark', level: 0 })

  it('returns nothing when the terminal is narrower than the banner', () => {
    expect(renderBanner({ columns: BANNER_WIDTH - 1, palette })).toBeUndefined()
  })

  it('returns one line per banner row when it fits', () => {
    expect(renderBanner({ columns: 80, palette })).toHaveLength(BANNER_ROWS.length)
  })

  it('draws the wordmark in #20b8cd on a dark background at full colour', () => {
    const lines = renderBanner({
      columns: 80,
      palette: brandPalette({ background: 'dark', level: 3 }),
    })
    expect(lines?.join('\n')).toContain('38;2;32;184;205')
  })

  it('draws the wordmark in #196872 on a light background at full colour', () => {
    const lines = renderBanner({
      columns: 80,
      palette: brandPalette({ background: 'light', level: 3 }),
    })
    expect(lines?.join('\n')).toContain('38;2;25;104;114')
  })

  it('falls back to plain cyan at 16 colours on either background', () => {
    for (const background of ['dark', 'light'] as const) {
      const lines = renderBanner({ columns: 80, palette: brandPalette({ background, level: 1 }) })
      expect(lines?.join('\n')).toContain(`${ESCAPE}36m`)
      expect(lines?.join('\n')).not.toContain('38;')
    }
  })

  it('holds no escape code at colour level 0', () => {
    const lines = renderBanner({ columns: 80, palette })
    for (const line of lines ?? []) expect(line).not.toContain('\x1b')
  })
})

describe('colorLevelFor', () => {
  it('is 0 when NO_COLOR is set on a terminal', () => {
    expect(colorLevelFor({ NO_COLOR: '1' }, tty, 3)).toBe(0)
  })

  it('is 0 when NO_COLOR is set even with FORCE_COLOR', () => {
    expect(colorLevelFor({ NO_COLOR: '1', FORCE_COLOR: '3' }, tty, 3)).toBe(0)
  })

  it('is 0 without a terminal', () => {
    expect(colorLevelFor({}, pipe, 3)).toBe(0)
  })

  it('takes FORCE_COLOR as the level without a terminal', () => {
    expect(colorLevelFor({ FORCE_COLOR: '1' }, pipe, 0)).toBe(1)
  })

  it("is the stream's supported level on a terminal", () => {
    expect(colorLevelFor({}, tty, 2)).toBe(2)
  })

  it('ignores an empty NO_COLOR', () => {
    expect(colorLevelFor({ NO_COLOR: '' }, tty, 3)).toBe(3)
  })
})

describe('brandPalette status colours', () => {
  const marks = (background: 'dark' | 'light' | undefined) => {
    const palette = brandPalette({ background, level: 3 })
    return [palette.success('s'), palette.failure('f'), palette.warning('w')].join('')
  }

  it('use the dashboard dark set on a dark background', () => {
    const text = marks('dark')
    for (const code of ['38;2;48;209;88', '38;2;255;69;58', '38;2;255;214;10']) {
      expect(text).toContain(code)
    }
  })

  it('use the dashboard light set on a light background', () => {
    const text = marks('light')
    for (const code of ['38;2;52;199;89', '38;2;255;59;48', '38;2;255;149;0']) {
      expect(text).toContain(code)
    }
  })

  it('use the dark set when the background is unknown', () => {
    expect(marks(undefined)).toBe(marks('dark'))
  })
})

describe('brandPalette chevron', () => {
  it('is #2ba0ab when the background was not measured', () => {
    expect(brandPalette({ background: 'dark', level: 3 }).chevron('›')).toContain('38;2;43;160;171')
  })

  it('is the primary mixed halfway into the measured background', () => {
    const palette = brandPalette({ background: 'light', rgb: { r: 1, g: 1, b: 1 }, level: 3 })
    expect(palette.chevron('›')).toContain('38;2;140;180;185')
  })
})
