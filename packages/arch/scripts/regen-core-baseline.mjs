import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  classifySpecifier,
  configFilesFor,
  extractSpecifiers,
  sourceFilesFor,
} from '../src/lint/extract-specifiers.ts'
import { HOST_EXTERNALS, matchesDenylistEntry } from '../src/lint/denylist.ts'
import { NATIVE_STORE_DENYLIST } from '../src/contract-types.ts'
import {
  AGENT_QA_CORE_SCOPED_HOST_BASELINE,
  inScopedHostBaseline,
} from '../src/core-host-scoped-baseline.ts'
import { AGENT_QA_CORE_MIGRATION_LEDGER } from '../../core/src/ownership-contract.ts'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(scriptDir, '../../..')
const packageDir = 'packages/core'
const baselinePath = resolve(scriptDir, '../src/core-host-baseline.ts')
const ledgerTargets = new Set(AGENT_QA_CORE_MIGRATION_LEDGER.map(entry => entry.target))

const files = [
  ...sourceFilesFor(packageDir, repoRoot),
  ...configFilesFor(packageDir, repoRoot),
]
const baseline = new Set()

for (const hit of files.flatMap(extractSpecifiers)) {
  if (inScopedHostBaseline(hit, AGENT_QA_CORE_SCOPED_HOST_BASELINE)) continue
  const classified = classifySpecifier(hit.specifier)

  if (classified.kind === 'node') {
    baseline.add(hit.specifier)
    continue
  }

  if (classified.kind !== 'external') {
    continue
  }

  if (ledgerTargets.has(classified.pkgName)) {
    continue
  }

  if (
    HOST_EXTERNALS.has(classified.pkgName) ||
    NATIVE_STORE_DENYLIST.some(entry => matchesDenylistEntry(classified.pkgName, entry))
  ) {
    baseline.add(classified.pkgName)
  }
}

const values = [...baseline].sort()
const source = [
  '// Generated by `node packages/arch/scripts/regen-core-baseline.mjs`.',
  "// This is core's regenerable source-level host/storage debt record, not a general allowance.",
  '// Clearance map: memory/* -> M2; parser/*, suite/*, hooks/*, and reporter/* -> M1.',
  '// A host module only one core file may import is in core-host-scoped-baseline.ts instead.',
  'export const AGENT_QA_CORE_HOST_BASELINE = [',
  ...values.map(value => `  '${value}',`),
  '] as const satisfies readonly string[]',
  '',
].join('\n')

writeFileSync(baselinePath, source)
console.log(`Wrote ${values.length} baseline entries to ${baselinePath}`)
